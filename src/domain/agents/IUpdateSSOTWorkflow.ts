/**
 * IUpdateSSOTWorkflow — Domain port for LATS Consensus-based SSOT updates.
 *
 * When auto-updating critical SSOT files (architecture.md, CONTEXT_INDEX.json, etc.),
 * the system must not apply the first candidate blindly. This workflow uses LATS
 * (Language Agent Tree Search) to generate multiple candidate updates, evaluates
 * each through ICriticFeedbackService for contradictions with DI_TOKENS and
 * architectural invariants, and selects the highest-confidence variant.
 *
 * Workflow:
 *   1. Request SSOT update with target file + proposed content
 *   2. Generate N candidate variants (default: 3) via LATS tree branching
 *   3. Evaluate each variant via ICriticFeedbackService (contradiction check)
 *   4. Score variants: higher confidence = fewer contradictions
 *   5. Select best variant (highest confidence above threshold)
 *   6. Return selected variant or reject if none pass threshold
 *
 * Academic Basis:
 *   - Zhou et al. (2024) "Language Agent Tree Search" arXiv:2310.04406
 *   - CC-002 Cross-Model QA pattern (IMultiModelConsensus)
 *
 * @layer Domain (Agents)
 * @pattern LATS Consensus Policy (SOTA 2026 — Multi-Variant SSOT Validation)
 * @see src/domain/ai/ITreeOfThoughts.ts — tree search engine
 * @see src/domain/audit/ICriticFeedbackService.ts — contradiction analysis
 */

// ─── Types ───────────────────────────────────────────────────────────────────

/**
 * Request to update an SSOT file with consensus validation.
 */
export interface SSOTUpdateRequest {
  /** Path to the SSOT file being updated (relative to project root). */
  readonly targetFile: string;
  /** The section or region being updated (for scoped changes). */
  readonly targetSection?: string;
  /** Proposed new content for the section. */
  readonly proposedContent: string;
  /** Context about why the update is needed. */
  readonly updateReason: string;
  /** Number of candidate variants to generate (default: 3). */
  readonly candidateCount?: number;
  /** Minimum confidence threshold to accept a variant (default: 0.7). */
  readonly minConfidence?: number;
  /** Max LATS retry iterations when all candidates are rejected (default: 0 = no retry). */
  readonly maxRetries?: number;
}

/**
 * A single candidate variant generated by LATS.
 */
export interface SSOTCandidate {
  /** Unique ID for this candidate. */
  readonly candidateId: string;
  /** Generated content variant. */
  readonly content: string;
  /** Confidence score from critic evaluation [0.0, 1.0]. */
  readonly confidence: number;
  /** Rationale for the confidence score. */
  readonly rationale: string;
  /** Contradictions found by the critic (if any). */
  readonly contradictions: readonly string[];
  /** Duration of evaluation in milliseconds. */
  readonly evaluationMs: number;
}

/**
 * Decision from the consensus workflow.
 */
export type SSOTUpdateDecision = 'accepted' | 'rejected' | 'needs_review';

/**
 * Result of SSOT update consensus evaluation.
 */
export interface SSOTUpdateResult {
  /** Final decision. */
  readonly decision: SSOTUpdateDecision;
  /** Selected candidate (if accepted). */
  readonly selectedCandidate?: SSOTCandidate;
  /** All evaluated candidates, sorted by confidence (descending). */
  readonly candidates: readonly SSOTCandidate[];
  /** Target file path. */
  readonly targetFile: string;
  /** Total evaluation duration in milliseconds. */
  readonly totalDurationMs: number;
  /** Number of LATS retry iterations used (0 if accepted on first pass). */
  readonly retriesUsed: number;
  /** ISO timestamp. */
  readonly evaluatedAt: string;
}

// ─── Interface ───────────────────────────────────────────────────────────────

/**
 * IUpdateSSOTWorkflow — consensus-based SSOT file update with LATS tree search.
 *
 * Usage:
 *   const workflow = container.resolve<IUpdateSSOTWorkflow>(DI_TOKENS.IUpdateSSOTWorkflow);
 *   const result = await workflow.evaluateUpdate(request, correlationId);
 *   if (result.decision === 'accepted') {
 *     applyUpdate(result.selectedCandidate!.content);
 *   }
 */
/** @experimental — no production consumer. Registered only when ENABLE_EXPERIMENTAL_PORTS=true. */
export interface IUpdateSSOTWorkflow {
  /**
   * Evaluate a proposed SSOT update using LATS consensus.
   *
   * Generates candidate variants, evaluates each for contradictions,
   * and selects the highest-confidence variant above threshold.
   *
   * @param request - Update request with target file and proposed content
   * @param correlationId - Request correlation for tracing
   * @returns Evaluation result with decision and candidates
   */
  evaluateUpdate(
    request: SSOTUpdateRequest,
    correlationId: string,
  ): Promise<SSOTUpdateResult>;
}

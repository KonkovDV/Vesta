/**
 * SymbioticProtocolAdapter — Infrastructure implementation of ISymbioticProtocol.
 *
 * Layer: Infrastructure
 *
 * Implements Phase 11: GENERATE_SIDECAR of the Extraction Pipeline.
 * Analyzes legacy systems via ts-morph AST parsing and generates
 * TypeScript Sidecar Adapters (event_bridge, di_wrapper, health_probe,
 * metrics_exporter) that wrap legacy modules with MicroPhoenix patterns
 * (Event Sourcing, DI, health checks, metrics).
 *
 * This is the core "Inverse Symbiosis" adapter — instead of absorbing
 * external code, MicroPhoenix projects its capabilities outward into
 * legacy systems via auto-generated adapter wrappers.
 *
 * Uses constructor injection for all dependencies (Hard Rule #13).
 * Events are persisted via IEventStore.saveEvents() (Outbox-first, Hard Rule #4).
 * All donor paths validated against external/ boundary (path traversal prevention).
 *
 * @see src/domain/extraction/ISymbioticProtocol.ts — Domain port
 * @see PLANS/DOCS_AUDIT_2026/83_HYPERDEEP_SYMBIOTIC_PROTOCOL_IMPLEMENTATION_PLAN.md
 * @see PLANS/DOCS_AUDIT_2026/71_EXTRACTION_V5_SOTA_AUDIT_MARCH_2026.md §2.3
 */

